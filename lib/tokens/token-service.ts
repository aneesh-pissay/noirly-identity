import { getEnv } from "@/lib/config/env";
import { generateSecureToken, hashToken } from "@/lib/security/crypto";
import { AccessToken } from "@/models/AccessToken";
import { RefreshToken } from "@/models/RefreshToken";
import { Session } from "@/models/Session";
import { recordEvent } from "@/lib/audit/event-log";
import { noteTokenIssued } from "@/lib/account/app-access";
import { notifySessionsEnded } from "@/lib/oidc/backchannel-logout";
import { signJwtAccessToken } from "@/lib/tokens/jwt-access-token";
import type { Types } from "mongoose";

export async function issueAccessToken(input: {
  clientId: string;
  userId: Types.ObjectId | string;
  sessionId: Types.ObjectId | string;
  scope: string;
  /**
   * For an API (RFC 8707): a signed JWT access token (RFC 9068) with `aud` set
   * to it, which the API verifies offline. Without it, an opaque token for
   * Identity's own endpoints.
   */
  resource?: { identifier: string; ttlSeconds: number; authTime: Date; methods: readonly string[] };
  /** Organization context (lib/oauth/org-context.ts) and its claims for a JWT. */
  organization?: { id: string; claims: Record<string, unknown> } | null;
}): Promise<{ token: string; expiresIn: number }> {
  const env = getEnv();
  const now = Date.now();
  let token: string;
  let expiresIn = env.ACCESS_TOKEN_TTL_SECONDS;
  if (input.resource) {
    // Never outliving the session: an API verifying offline can't ask.
    const session = await Session.findById(input.sessionId).select("expiresAt").lean();
    const sessionLeft = session ? Math.floor((session.expiresAt.getTime() - now) / 1000) : 0;
    expiresIn = Math.max(1, Math.min(input.resource.ttlSeconds, sessionLeft));
    token = await signJwtAccessToken({
      audience: input.resource.identifier,
      clientId: input.clientId,
      userId: String(input.userId),
      sessionId: input.sessionId,
      scope: input.scope,
      expiresIn,
      authTime: input.resource.authTime,
      methods: input.resource.methods,
      extraClaims: input.organization?.claims,
    });
  } else {
    token = generateSecureToken(32);
  }
  await AccessToken.create({
    tokenHash: hashToken(token),
    clientId: input.clientId,
    userId: input.userId,
    sessionId: input.sessionId,
    scope: input.scope,
    audience: input.resource?.identifier ?? null,
    organizationId: input.organization?.id ?? null,
    expiresAt: new Date(now + expiresIn * 1000),
  });
  // Every way an app gets a token (code, refresh, mobile) comes through here.
  await noteTokenIssued(input.userId, input.clientId, input.scope);
  await Session.updateOne({ _id: input.sessionId }, { $addToSet: { appIds: input.clientId } });
  return { token, expiresIn };
}

export async function resolveAccessToken(token: string) {
  const record = await AccessToken.findOne({ tokenHash: hashToken(token) });
  if (!record || record.revokedAt || record.expiresAt.getTime() <= Date.now()) {
    return null;
  }
  // A token for another API (its `aud`) isn't good at Identity's own endpoints,
  // nor is an app's own (machine) token, which speaks for no one.
  if (record.audience || !record.userId || !record.sessionId) return null;
  // A token lives no longer than its session: signing out everywhere, or a
  // password change or reset, must cut off apps at once, not an hour later.
  const live = await Session.exists({
    _id: record.sessionId,
    revokedAt: null,
    expiresAt: { $gt: new Date() },
  });
  if (!live) return null;
  return record as typeof record & { userId: Types.ObjectId; sessionId: Types.ObjectId };
}

export async function revokeAccessTokensForSession(
  sessionId: Types.ObjectId | string,
): Promise<void> {
  await AccessToken.updateMany(
    { sessionId, revokedAt: null },
    { revokedAt: new Date() },
  );
}

export async function issueRefreshToken(input: {
  clientId: string;
  userId: Types.ObjectId | string;
  sessionId: Types.ObjectId | string;
  scope: string;
  familyId?: string;
  /** Pre-generated by rotation, which records its hash on the old token first. */
  token?: string;
  /** APIs the grant covers (RFC 8707). */
  resources?: string[];
  organizationId?: Types.ObjectId | string | null;
}): Promise<{ token: string; familyId: string }> {
  const env = getEnv();
  const token = input.token ?? generateSecureToken(40);
  const familyId = input.familyId ?? generateSecureToken(16);
  await RefreshToken.create({
    tokenHash: hashToken(token),
    familyId,
    clientId: input.clientId,
    userId: input.userId,
    sessionId: input.sessionId,
    scope: input.scope,
    resources: input.resources ?? [],
    organizationId: input.organizationId ?? null,
    expiresAt: new Date(Date.now() + env.REFRESH_TOKEN_TTL_SECONDS * 1000),
  });
  return { token, familyId };
}

type FamilyMember = { userId: unknown; clientId: string; familyId: string; sessionId: Types.ObjectId };

/**
 * Ends a refresh token family: every refresh token in it, and every access
 * token the app holds through that session, however it got them.
 */
async function revokeFamily(token: FamilyMember, extra: Record<string, unknown> = {}) {
  const now = new Date();
  const [refresh, access] = await Promise.all([
    RefreshToken.updateMany({ familyId: token.familyId, revokedAt: null }, { $set: { revokedAt: now, ...extra } }),
    AccessToken.updateMany({ sessionId: token.sessionId, clientId: token.clientId, revokedAt: null }, { $set: { revokedAt: now } }),
  ]);
  return { refreshTokens: refresh.modifiedCount, accessTokens: access.modifiedCount };
}

/**
 * A refresh token used twice: someone else may hold it. The whole family is
 * revoked everywhere: refresh tokens, the app's access tokens through that
 * session, and the app's own session (told by back-channel logout). Identity
 * and other apps stay signed in; the leak was at this app.
 */
async function handleReuse(token: FamilyMember, extra: Record<string, unknown> = {}) {
  const revoked = await revokeFamily(token, extra);
  await notifySessionsEnded([{ _id: token.sessionId, userId: token.userId, appIds: [token.clientId] }], { onlyClientId: token.clientId });
  await recordEvent({ action: "oauth.refresh_reuse_detected", subjectId: String(token.userId), actorId: null, clientId: token.clientId, data: { familyId: token.familyId, familyRevoked: true, accessTokensRevoked: revoked.accessTokens } });
}

/** Revokes a refresh token's whole family (RFC 7009: the grant, not just the token). */
export async function revokeRefreshFamily(rawToken: string, clientId?: string) {
  const token = await RefreshToken.findOne({ tokenHash: hashToken(rawToken) });
  // Only the app it was issued to may revoke it.
  if (!token || (clientId && token.clientId !== clientId)) return false;
  await revokeFamily(token);
  return true;
}

export async function rotateRefreshToken(rawToken: string, clientId: string) {
  const existing = await RefreshToken.findOne({ tokenHash: hashToken(rawToken) });
  if (!existing) {
    return { error: "invalid_grant" as const };
  }

  if (existing.clientId !== clientId) {
    return { error: "invalid_grant" as const };
  }

  if (existing.expiresAt.getTime() <= Date.now()) {
    return { error: "invalid_grant" as const };
  }

  // Reuse detection: previously rotated/revoked token presented again.
  if (existing.revokedAt || existing.replacedByTokenHash) {
    existing.reuseDetectedAt = new Date();
    await existing.save();
    await handleReuse(existing);
    return { error: "reuse_detected" as const, familyId: existing.familyId };
  }

  // A refresh token lives no longer than its session. Ended some other way
  // (expired, say): nothing new is minted, and the family goes with it.
  const sessionLive = await Session.exists({ _id: existing.sessionId, revokedAt: null, expiresAt: { $gt: new Date() } });
  if (!sessionLive) {
    await revokeFamily(existing);
    return { error: "invalid_grant" as const };
  }

  // Claim the old token atomically before minting its successor. Two requests
  // racing with one token (a thief and the real app) can't both rotate it; the
  // loser is handled as reuse, which revokes the whole family.
  const nextToken = generateSecureToken(40);
  const claimed = await RefreshToken.findOneAndUpdate(
    { _id: existing._id, revokedAt: null, replacedByTokenHash: null },
    { $set: { revokedAt: new Date(), replacedByTokenHash: hashToken(nextToken) } },
  );
  if (!claimed) {
    await handleReuse(existing, { reuseDetectedAt: new Date() });
    return { error: "reuse_detected" as const, familyId: existing.familyId };
  }

  const next = await issueRefreshToken({
    clientId: existing.clientId,
    userId: existing.userId,
    sessionId: existing.sessionId,
    scope: existing.scope,
    familyId: existing.familyId,
    token: nextToken,
    resources: existing.resources ?? [],
    organizationId: existing.organizationId ?? null,
  });

  return {
    error: null,
    previous: existing,
    refreshToken: next.token,
    familyId: next.familyId,
  };
}

export async function revokeRefreshTokensForSession(
  sessionId: Types.ObjectId | string,
): Promise<void> {
  await RefreshToken.updateMany(
    { sessionId, revokedAt: null },
    { revokedAt: new Date() },
  );
}
